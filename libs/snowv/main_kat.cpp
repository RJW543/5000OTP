/* Helpers                                                              */
/* ------------------------------------------------------------------ */

static void print_hex(const char *label, const u8 *data, int len)
{
    printf("%s", label);
    for (int i = 0; i < len; i++)
        printf("%02x ", data[i]);
    printf("\n");
}

/*
 * Run one KAT: initialise with key/iv, generate (skip * 16) bytes of
 * initialisation keystream (already consumed inside keyiv_setup), then
 * produce (n_words * 16) bytes and compare against expected[].
 *
 * The paper's "Keystream phase, z = ..." begins immediately after
 * keyiv_setup() returns, so skip = 0 here.
 */
static int run_kat(const char *name,
                   u8 *key,     /* 32 bytes */
                   u8 *iv,      /* 16 bytes */
                   const u8 *expected,
                   int n_words) /* number of 16-byte blocks to check */
{
    struct SnowV32 snowv;
    snowv.keyiv_setup(key, iv, 0);

    u8 got[8 * 16]; /* up to 128 bytes */
    for (int i = 0; i < n_words; i++)
        snowv.keystream(&got[i * 16]);

    int pass = (memcmp(got, expected, n_words * 16) == 0);

    printf("[KAT] %s: %s\n", name, pass ? "PASS" : "FAIL");
    if (!pass)
    {
        print_hex("  Expected: ", expected, n_words * 16);
        print_hex("  Got:      ", got,      n_words * 16);
    }
    return pass;
}

