// snowvi_kat.cpp — SNOW-Vi Known-Answer Test.
//
// Runs the portable SNOW-Vi core (libs/snowv/snow-vi.h) against the official
// keystream-phase test vectors from the paper (Ekdahl, Maximov, Johansson,
// Yang, WiSec'21 / IACR ePrint 2021/236, Appendix C, Listing 5). Non-AEAD mode.
// Vectors #1 (key=iv=0) and #2 (key=iv=0xff) are checked in full (8 blocks).
//
// Exit status 0 = all pass, 1 = any mismatch.
#include "snow-vi.h"
#include <cstdio>
#include <cstring>

static int check(const char* name, const unsigned char key[32],
                 const unsigned char iv[16], const unsigned char exp[8][16]) {
    SnowVi s;
    s.keyiv_setup(key, iv, /*aead=*/0);
    int ok = 1;
    for (int t = 0; t < 8; t++) {
        SnowVi::V z = s.keystream();
        if (memcmp(z.b, exp[t], 16)) ok = 0;
    }
    printf("  %-24s %s\n", name, ok ? "PASS" : "FAIL");
    return ok;
}

